import 'dart:io';

/// Compile the existing normative software catalog and SQL into the native
/// engine. Runtime installations never depend on the source checkout.
void main() {
  const source = 'docs/decisions/relational-storage';
  final sql = [
    'typed',
    'kernel',
    'semantic',
    'workflow',
  ].map((name) => File('$source/$name.sql').readAsStringSync()).join('\n');
  final catalog = File('$source/catalog.json').readAsStringSync();
  for (final value in [sql, catalog]) {
    if (value.contains("'''")) {
      throw StateError(
        'Schema resource contains the Dart raw-string delimiter',
      );
    }
  }
  File('packages/ub_store/lib/src/schema.g.dart')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(
      '// Generated by tool/embed_schema.dart from the normative schema.\n'
      '// Do not edit this copy; change the owning schema and regenerate.\n'
      "const sqliteSchema = r'''$sql''';\n"
      "const relationalCatalog = r'''$catalog''';\n",
    );
}
